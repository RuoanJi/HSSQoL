"""Builds ports.md and ports.html from BepInEx/hssqol-data.json (HSSQoL DataDump).

Port layout data:
  City.wharfInfo_[stage] = {mapIndex_, area_: [WharfArea ids], hide_}; only the home port (王国的据点) has several stages.
  WharfArea.type_: 0 = fixed building (defBlockIndex_ -> WharfBlock), 1 = empty lot (空地, buildable), 2 = dungeon entrance
  (course_ = CourseData ids). WharfBlock = building catalog (type_ 1 = shop/house; destruct_ 0 = player-buildable).
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
# Game folder: HSS_GAME_DIR, else the one this repo sits in (<game>/workspace/src/HSSQoL/docs).
GAME = os.environ.get('HSS_GAME_DIR') or os.path.join(HERE, '..', '..', '..', '..')
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(GAME, 'BepInEx', 'hssqol-data.json')
d = json.load(open(SRC, encoding='utf-8'))

WA = {w['id_']: w for w in d['wharfAreaList_']}
WB = {b['id_']: b for b in d['wharfBlockList_']}
CO = {c['id_']: c for c in d['courseDataList_']}
LAND = {l['id_']: l['name_'] for l in d['landList_']}
KIND = {0: 'fixed', 1: 'lot', 2: 'dungeon'}


def land_of(city):
    return LAND.get(city['landIndex_']) or next((l['name_'] for l in d['landList_'] if city['id_'] in l['citys_']), '')


def stage(info):
    lots, fslots, fixed, dungeons = 0, 0, [], []
    for a in info['area_']:
        w = WA[a]
        if w['type_'] == 1: lots += 1
        elif w['type_'] == 0:
            b = WB[w['defBlockIndex_']]
            fixed.append(b['name_'])
            if b['type_'] == 1: fslots += 1  # shops/houses occupy a building plot; 王宫 (type 3) does not
        else:
            for cid in w['course_']:
                c = CO[cid]
                dungeons.append({'id': cid, 'name': c['name_'], 'lv': c['lv_'], 'cost': c['costValue_'], 'needRank': c['costRank_']})
    return {'lots': lots, 'slots': lots + fslots, 'fixed': fixed, 'dungeons': dungeons}


ports = []
for c in d['cityList_']:
    stages = [stage(i) for i in c['wharfInfo_']]
    last = stages[-1]
    ports.append({'id': c['id_'], 'name': c['name_'], 'land': land_of(c), 'snow': c['snowLand_'] == 0,
                  'lots': last['lots'], 'slots': last['slots'], 'fixed': last['fixed'], 'dungeons': last['dungeons'],
                  'stages': [[s['slots'], s['lots']] for s in stages] if len(stages) > 1 else None})

catalog = []
for b in d['wharfBlockList_']:
    if b['type_'] != 1 or b['destruct_'] != 0: continue
    catalog.append({'id': b['id_'], 'name': b['name_'], 'explain': b['explain_'].strip(), 'unlockLv': b['unlockLv_'],
                    'unlockPrice': b['unLockPrice_'], 'buildTime': b['buildTime_'],
                    'levels': [[i['needExp_'], i['power_']] for i in b['blockInfo_']]})

# ---------------------------------------------------------------- ports.md
M = ['# Ports (港口)\n',
     'Generated by `make_ports.py` from the game\'s data tables. Each port\'s map has three kinds of plots: '
     '**空地** (empty lots where you can build), **fixed buildings** that come with the port, and the **dungeon entrance**.\n',
     'The home port 王国的据点 grows in 5 stages; its lot count is listed per stage. Other ports have one layout.\n',
     '| 港口 | 地区 | 雪地 | 建筑位 (total) | 空地 (empty) | 固定建筑 | 迷宫 (count, Lv range, 体力) |',
     '|---|---|---|---:|---:|---|---|']
for p in ports:
    ds = p['dungeons']
    dsum = (f'{len(ds)} · Lv {min(x["lv"] for x in ds)}–{max(x["lv"] for x in ds)} · 体力 {min(x["cost"] for x in ds)}–{max(x["cost"] for x in ds)}' if ds else '—')
    slots = str(p['slots']) + (f' (stages: {" → ".join(str(t) for t, _ in p["stages"])})' if p['stages'] else '')
    M.append(f'| {p["name"]} | {p["land"] or "—"} | {"是" if p["snow"] else ""} | {slots} | {p["lots"]} | {"、".join(p["fixed"]) or "—"} | {dsum} |')
M.append(f'\nTotal: {sum(p["slots"] for p in ports)} building plots ({sum(p["lots"] for p in ports)} of them empty at the start) across {len(ports)} ports. '
         '建筑位 = empty lots + plots holding a fixed shop/house (王宫 not counted).\n')
M.append('\n# Dungeons per port\n')
for p in ports:
    if not p['dungeons']: continue
    M.append(f'\n**{p["name"]}**' + (f'（{p["land"]}）' if p['land'] else '') + ': ' +
             '、'.join(f'#{x["id"]} {x["name"]} (Lv {x["lv"]}, 体力 {x["cost"]}' + (f', 船团等级≥{x["needRank"]}' if x['needRank'] else '') + ')' for x in p['dungeons']))
M.append('\n# Buildings you can build on 空地\n')
M.append('Unlock = the building\'s required level (`unlockLv_`) and unlock price (`unLockPrice_`), as stored in the data. '
         'Each building has 5 levels; a level needs the listed experience and adds the listed 势力 (power).\n')
M.append('| 建筑 | 说明 | 解锁等级 | 解锁价格 | 建造时间 | 每级 经验 / 势力 |\n|---|---|---:|---:|---:|---|')
for b in catalog:
    M.append(f'| {b["name"]} | {b["explain"]} | {b["unlockLv"]} | {b["unlockPrice"]:,} | {b["buildTime"]} | ' +
             ' · '.join(f'{e:,}/{pw}' for e, pw in b['levels']) + ' |')
open(os.path.join(HERE, 'ports.md'), 'w', encoding='utf-8').write('\n'.join(M) + '\n')

# ---------------------------------------------------------------- ports.html
tpl = open(os.path.join(HERE, 'ports_template.html'), encoding='utf-8').read()
pay = json.dumps({'ports': ports, 'catalog': catalog}, ensure_ascii=False, separators=(',', ':')).replace('</', '<' + chr(92) + '/')
open(os.path.join(HERE, 'ports.html'), 'w', encoding='utf-8').write(tpl.replace('/*PORT_DATA*/null', pay))
print('ports ok', len(ports), sum(p['slots'] for p in ports), sum(p['lots'] for p in ports), len(catalog))
